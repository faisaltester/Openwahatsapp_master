/** Return an inline SVG string for `name` (empty string for unknown names). */
export function icon(name, size = 16, extraClass = '') {
  const body = PATHS[name];
  if (!body) return '';
  return `<svg class="ico ${extraClass}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

/** Replace every <i data-icon="name" data-size="n"> placeholder under `root` with its SVG. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach(el => {
    const html = icon(el.dataset.icon, Number(el.dataset.size) || 16, el.className || '');
    if (html) el.outerHTML = html;
  });
}
